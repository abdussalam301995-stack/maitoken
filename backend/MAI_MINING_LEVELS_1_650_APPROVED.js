function getMiningLevelForHolding(totalHolding) {
  const holding = Math.max(0, Number(totalHolding) || 0);
  let lo = 0;
  let hi = MAI_MINING_LEVELS.length - 1;
  let best = 0;

  while (lo <= hi) {
    const mid = Math.floor((lo + hi) / 2);
    if (MAI_MINING_LEVELS[mid].requiredHolding <= holding) {
      best = mid;
      lo = mid + 1;
    } else {
      hi = mid - 1;
    }
  }

  return MAI_MINING_LEVELS[best];
}

function getMiningLevel(level) {
  const n = Math.max(1, Math.min(650, Math.trunc(Number(level) || 1)));
  return MAI_MINING_LEVELS[n - 1];
}

